"""Concrete static, spherically symmetric wormhole geometries.

Each family supplies the local data (r, r', r'', Phi', Phi'') as numpy functions of the
proper radial distance l (l = 0 at the throat, metres).  Derivatives are generated by sympy
from one closed-form expression, so they cannot drift out of step with the definition.

Families (all with throat radius r0 at l = 0):
  ellis(r0)                    r = sqrt(l^2 + r0^2),  Phi = 0             (Ellis 1973; Bronnikov 1973)
  gen_ellis(r0, n)             r = (l^n + r0^n)^(1/n), n even             flatter throat for n > 2
  two_scale(r0, eps, L)        r^2 = r0^2 + (eps/2) l^2 + (1 - eps/2) l^4 / (l^2 + L^2)
                               flare-out 1 - b'(r0) = eps at the throat, ordinary flare beyond L
  redshift_ellis(r0, phi_a, w) Ellis shape with Phi = phi_a exp(-l^2/w^2)  (strong radial tide)
  thin_band(r0, a0)            Morris-Thorne's "absurdly benign" wormhole, given in Schwarzschild
                               gauge: b(r) = r0 (1 - (r - r0)/a0)^2 on [r0, r0 + a0], b = 0 beyond,
                               Phi = 0 (Morris & Thorne 1988, the example Ford & Roman 1996 audit)
"""
from dataclasses import dataclass, field
from typing import Callable

import numpy as np
import sympy as sp

_l = sp.symbols("l", real=True)


@dataclass
class Geometry:
    name: str
    r0: float
    params: dict
    _f: Callable = field(repr=False)          # l -> (r, r', r'', Phi', Phi'', Phi)
    l_max: float = 50.0                       # metres: region where the geometry matters

    def local(self, l):
        r, rp, rpp, Pp, Ppp, P = self._f(np.asarray(l, dtype=float))
        return r, rp, rpp, Pp, Ppp

    def Phi(self, l):
        return self._f(np.asarray(l, dtype=float))[5]


def _from_expr(name, r0, params, r_expr, Phi_expr, l_max=50.0):
    funcs = [r_expr, sp.diff(r_expr, _l), sp.diff(r_expr, _l, 2),
             sp.diff(Phi_expr, _l), sp.diff(Phi_expr, _l, 2), Phi_expr]
    lam = sp.lambdify(_l, funcs, "numpy")

    def f(l):
        vals = lam(l)
        return tuple(np.broadcast_to(np.asarray(v, dtype=float), np.shape(l)).copy() for v in vals)

    return Geometry(name, r0, params, f, l_max)


def ellis(r0=1.0):
    return _from_expr("ellis", r0, {}, sp.sqrt(_l**2 + r0**2), sp.Integer(0), l_max=200 * r0)


def gen_ellis(r0=1.0, n=4):
    assert n % 2 == 0 and n >= 2
    return _from_expr(f"gen_ellis_n{n}", r0, {"n": n}, (_l**n + r0**n) ** sp.Rational(1, n),
                      sp.Integer(0), l_max=200 * r0)


def two_scale(r0=1.0, eps=0.01, L=10.0):
    e = sp.nsimplify(eps)
    r2 = r0**2 + e / 2 * _l**2 + (1 - e / 2) * _l**4 / (_l**2 + L**2)
    return _from_expr(f"two_scale_eps{eps:g}_L{L:g}", r0, {"eps": eps, "L": L}, sp.sqrt(r2),
                      sp.Integer(0), l_max=200 * max(r0, L))


def two_scale_redshift(r0=1.0, eps=0.01, L=10.0, phi2=0.0, w=3.0):
    """two_scale with a Gaussian redshift dip, Phi = phi_a exp(-l^2/w^2) with phi_a = -phi2 w^2/2, so that
    Phi''(0) = phi2 and the dip is phi2 w^2/2 deep.  Used to test the scope of the throat theorem."""
    e = sp.nsimplify(eps)
    r2 = r0**2 + e / 2 * _l**2 + (1 - e / 2) * _l**4 / (_l**2 + L**2)
    phi_a = -sp.nsimplify(phi2) * sp.nsimplify(w) ** 2 / 2
    return _from_expr(f"two_scale_red_eps{eps:g}_p{phi2:g}", r0, {"eps": eps, "L": L, "phi2": phi2, "w": w},
                      sp.sqrt(r2), phi_a * sp.exp(-_l**2 / sp.nsimplify(w) ** 2), l_max=200 * max(r0, L))


def redshift_ellis(r0=1.0, phi_a=0.0, w=1.0):
    return _from_expr(f"redshift_ellis_a{phi_a:g}_w{w:g}", r0, {"phi_a": phi_a, "w": w},
                      sp.sqrt(_l**2 + r0**2), phi_a * sp.exp(-_l**2 / w**2), l_max=200 * r0)


class ThinBand:
    """Morris-Thorne 'absurdly benign' wormhole (Phi = 0), handled in Schwarzschild gauge.

    For r0 <= r <= r0 + a0:  b = r0 (1 - y)^2, y = (r - r0)/a0;  b = 0 for r > r0 + a0.
    Local data follow from r' = sqrt(1 - b/r) and r'' = (b - b' r) / (2 r^2).
    The proper distance l(r) is computed by quadrature with the substitution r = r0 + s^2,
    which removes the integrable throat singularity of dl/dr.
    """

    def __init__(self, r0=1.0, a0=0.01):
        self.name = f"thin_band_a{a0:g}"
        self.r0, self.a0 = r0, a0
        self.params = {"a0": a0}
        self.l_max = 200 * r0
        # tabulate l(r) on a fine grid in s = sqrt(r - r0)
        s = np.concatenate([np.linspace(0, np.sqrt(a0), 4001)[:-1],
                            np.sqrt(a0) + np.linspace(0, np.sqrt(self.l_max), 4001)])
        r = r0 + s**2
        b = self.b(r)
        # dl = dr / sqrt(1 - b/r) = 2 s ds / sqrt(1 - b/r); near the throat 1 - b/r ~ (2/a0 + 1/r0) s^2
        with np.errstate(divide="ignore", invalid="ignore"):
            integrand = 2 * s / np.sqrt(np.clip(1 - b / r, 1e-300, None))
        integrand[0] = 2 / np.sqrt(2 / a0 + 1 / r0)
        l = np.concatenate([[0.0], np.cumsum(0.5 * (integrand[1:] + integrand[:-1]) * np.diff(s))])
        self._r_tab, self._l_tab = r, l

    def b(self, r):
        y = (np.asarray(r) - self.r0) / self.a0
        return np.where(y <= 1.0, self.r0 * (1 - np.clip(y, 0, 1)) ** 2, 0.0)

    def bprime(self, r):
        y = (np.asarray(r) - self.r0) / self.a0
        return np.where(y <= 1.0, -2 * self.r0 / self.a0 * (1 - np.clip(y, 0, 1)), 0.0)

    def r_of_l(self, l):
        return np.interp(np.abs(l), self._l_tab, self._r_tab)

    def local(self, l):
        l = np.asarray(l, dtype=float)
        r = self.r_of_l(l)
        b, bp = self.b(r), self.bprime(r)
        rp = np.sign(l) * np.sqrt(np.clip(1 - b / r, 0, None))
        rpp = (b - bp * r) / (2 * r**2)
        z = np.zeros_like(r)
        return r, rp, rpp, z, z

    def Phi(self, l):
        return np.zeros_like(np.asarray(l, dtype=float))


class Compact:
    """Throat whose exotic region is compact: flat space for |l| > a (zero ADM mass).

        r(l) = r0 + (2a/pi)(1 - cos(pi l / 2a))      for |l| <= a,
        r(l) = r0 + 2a/pi + (|l| - a)                for |l| > a,
    so r' = sin(pi l / 2a) rises from 0 to 1 and r'' = (pi/2a) cos(pi l/2a) >= 0 vanishes at
    |l| = a (C^2).  Flare-out at the throat: 1 - b'(r0) = 2 r0 r''(0) = pi r0 / a.
    Optional redshift Phi(l) = phi_a exp(-l^2/w^2): a well (phi_a < 0) or a bump (phi_a > 0).
    """

    def __init__(self, r0=1.0, a=1.0, phi_a=0.0, w=1.0):
        self.name = f"compact_a{a:g}" + (f"_phi{phi_a:g}_w{w:g}" if phi_a else "")
        self.r0, self.a, self.phi_a, self.w = r0, a, phi_a, w
        self.params = {"a": a, "phi_a": phi_a, "w": w}
        self.l_max = 200 * max(r0, a)

    def local(self, l):
        l = np.asarray(l, dtype=float)
        a, r0 = self.a, self.r0
        al = np.abs(l)
        inside = al <= a
        k = np.pi / (2 * a)
        r = np.where(inside, r0 + (1 - np.cos(k * al)) / k, r0 + 1 / k + (al - a))
        rp = np.sign(l) * np.where(inside, np.sin(k * al), 1.0)
        rpp = np.where(inside, k * np.cos(k * al), 0.0)
        P = self.phi_a * np.exp(-l**2 / self.w**2)
        Pp = -2 * l / self.w**2 * P
        Ppp = (4 * l**2 / self.w**4 - 2 / self.w**2) * P
        return r, rp, rpp, Pp, Ppp

    def Phi(self, l):
        l = np.asarray(l, dtype=float)
        return self.phi_a * np.exp(-l**2 / self.w**2)
