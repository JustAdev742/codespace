"""Build Ludora's music and sound effects into the web app.

    python3 -m venv .venv && . .venv/bin/activate && pip install -r requirements.txt
    python build.py

Renders every track in ludora_audio/tracks and every effect in
ludora_audio/sfx.py, encodes them as MP3 into web/src/assets/audio/ and writes
the manifest the web player reads, web/src/lib/sound/assets.generated.ts.

Needs FluidSynth, the MuseScore General soundfont and ffmpeg
(Debian/Ubuntu: apt install fluidsynth musescore-general-soundfont ffmpeg).
Renders are cached in tools/audio/.cache, so a rebuild after a small change is quick.
"""

from __future__ import annotations

import importlib
import json
import os
import subprocess
import tempfile
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np
import soundfile as sf

from ludora_audio import dsp, sfx
from ludora_audio.mixer import mix_song
from ludora_audio.render import CACHE, SR

HERE = Path(__file__).resolve().parent
WEB = HERE.parent.parent / "web"
ASSETS = WEB / "src" / "assets" / "audio"
MANIFEST = WEB / "src" / "lib" / "sound" / "assets.generated.ts"

# In the order the manifest lists them.
TRACKS = ["lobby", "game", "calm", "market", "battle", "intense", "results"]

# LAME variable bit rate: 4 is about 165 kbit/s, 5 about 130. Music is long and sits under everything;
# effects are short and carry the sparkle, so they get the higher quality.
MUSIC_QUALITY = 5
SFX_QUALITY = 4


def encode(audio: np.ndarray, out: Path, quality: int) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        wav = Path(tmp) / "in.wav"
        sf.write(wav, audio, SR, subtype="FLOAT")
        # bitexact keeps encoder version strings out of the file, so an unchanged sound encodes to the same bytes.
        subprocess.run(
            ["ffmpeg", "-v", "error", "-y", "-i", str(wav), "-map_metadata", "-1", "-fflags", "+bitexact", "-flags:a", "+bitexact", "-codec:a", "libmp3lame", "-q:a", str(quality), str(out)],
            check=True,
        )


def build_track(name: str) -> dict:
    song = importlib.import_module(f"ludora_audio.tracks.{name}").song()
    loop = mix_song(song)
    start, end = int(round(loop.loop_start * SR)), int(round(loop.loop_end * SR))
    encode(loop.audio, ASSETS / "music" / f"{name}.mp3", MUSIC_QUALITY)
    return {
        "id": song.id,
        "title": song.title,
        "bpm": song.bpm,
        "beatsPerBar": song.beats_per_bar,
        "bars": song.bars,
        "loopStart": round(loop.loop_start, 6),
        "loopEnd": round(loop.loop_end, 6),
        "lufs": round(dsp.lufs(loop.audio[start:end]), 1),
        "truePeak": round(dsp.true_peak_db(loop.audio), 1),
        "seam": round(dsp.seam_error_db(loop.audio, start, end), 1),
    }


def build_effect(name: str) -> dict:
    effect = next(e for e in sfx.effects() if e.name == name)
    audio = sfx.render(effect)
    encode(audio, ASSETS / "sfx" / f"{name}.mp3", SFX_QUALITY)
    info = {"name": name, "seconds": round(len(audio) / SR, 3), "play": effect.play, "lufs": round(dsp.lufs(audio), 1), "truePeak": round(dsp.true_peak_db(audio), 1)}
    if effect.play == "rise":
        # The moment the effect is written to land on (the end of the build), so the player can line it up.
        info["land"] = effect.seconds
    return info


def ident(prefix: str, name: str) -> str:
    """`lanternReveal-common` -> `sfxLanternRevealCommon`."""
    words = name.split("-")
    return prefix + "".join(w[:1].upper() + w[1:] for w in words)


def manifest(tracks: list[dict], effects: list[dict]) -> str:
    lines = [
        "// Generated by tools/audio/build.py from the scores in tools/audio/ludora_audio. Do not edit by hand:",
        "// change a track or an effect there and run the build again.",
        "",
    ]
    for t in tracks:
        lines.append(f"import {ident('music', t['id'])} from '../../assets/audio/music/{t['id']}.mp3';")
    for e in effects:
        lines.append(f"import {ident('sfx', e['name'])} from '../../assets/audio/sfx/{e['name']}.mp3';")
    lines += [
        "",
        "export type MusicId = " + " | ".join(f"'{t['id']}'" for t in tracks) + ";",
        "",
        "export interface MusicAsset {",
        "  url: string;",
        "  title: string;",
        "  bpm: number;",
        "  beatsPerBar: number;",
        "  bars: number;",
        "  /** The loop, in seconds into the file. The file has half a second of the music either side of it. */",
        "  loopStart: number;",
        "  loopEnd: number;",
        "}",
        "",
        "export interface SfxAsset {",
        "  url: string;",
        "  seconds: number;",
        "  /** 'once' plays from the start; 'rise' builds up to `land` seconds in, and can start part-way so it lands on time. */",
        "  play: 'once' | 'rise';",
        "  land?: number;",
        "}",
        "",
        "export const MUSIC_ASSETS: Record<MusicId, MusicAsset> = {",
    ]
    for t in tracks:
        lines.append(
            f"  {t['id']}: {{ url: {ident('music', t['id'])}, title: {json.dumps(t['title'])}, bpm: {t['bpm']}, beatsPerBar: {t['beatsPerBar']}, bars: {t['bars']}, loopStart: {t['loopStart']}, loopEnd: {t['loopEnd']} }},"
        )
    lines += ["};", "", "export const SFX_ASSETS = {"]
    for e in effects:
        key = e["name"] if e["name"].isidentifier() else f"'{e['name']}'"
        land = f", land: {e['land']}" if "land" in e else ""
        lines.append(f"  {key}: {{ url: {ident('sfx', e['name'])}, seconds: {e['seconds']}, play: '{e['play']}'{land} }},")
    lines += ["} satisfies Record<string, SfxAsset>;", "", "export type SfxAssetName = keyof typeof SFX_ASSETS;", ""]
    return "\n".join(lines)


def main() -> None:
    t0 = time.time()
    names = [e.name for e in sfx.effects()]
    assert len(names) == len(set(names)), "two effects share a name"
    workers = os.cpu_count() or 2
    with ProcessPoolExecutor(max_workers=workers) as pool:
        track_jobs = [pool.submit(build_track, t) for t in TRACKS]
        effect_jobs = [pool.submit(build_effect, n) for n in names]
        tracks = [j.result() for j in track_jobs]
        effects = [j.result() for j in effect_jobs]
    # Files from effects or tracks that no longer exist.
    keep = {ASSETS / "music" / f"{t}.mp3" for t in TRACKS} | {ASSETS / "sfx" / f"{n}.mp3" for n in names}
    for old in ASSETS.glob("*/*.mp3"):
        if old not in keep:
            old.unlink()
    # Cached renders this build did not use (every render it used was written or touched since it started).
    for stale in CACHE.glob("*.wav"):
        if stale.stat().st_mtime < t0 - 1:
            stale.unlink()
    MANIFEST.write_text(manifest(tracks, effects))
    for t in tracks:
        print(f"music {t['id']:<9} {t['title']:<20} {t['lufs']:>6} LUFS  peak {t['truePeak']:>5} dBTP  seam {t['seam']:>7} dB  {(ASSETS / 'music' / (t['id'] + '.mp3')).stat().st_size // 1024:>4} KB")
    total = sum((ASSETS / "sfx" / f"{e['name']}.mp3").stat().st_size for e in effects)
    loudest = max(effects, key=lambda e: e["truePeak"])
    print(f"{len(effects)} effects, {total // 1024} KB, loudest true peak {loudest['truePeak']} dBTP ({loudest['name']})")
    print(f"wrote {MANIFEST.relative_to(HERE.parent.parent)} in {time.time() - t0:.0f} s")


if __name__ == "__main__":
    main()
